package com.chaquo.python.model;

public class TaiLieu {
    private String idLoTrinh;
    private String tenTaiLieu;
    private String duongDan;
    private String loai;
    private String icon;
    private String moTa;

    public TaiLieu() {}

    public String getIdLoTrinh() { return idLoTrinh; }
    public void setIdLoTrinh(String idLoTrinh) { this.idLoTrinh = idLoTrinh; }

    public String getTenTaiLieu() { return tenTaiLieu; }
    public void setTenTaiLieu(String tenTaiLieu) { this.tenTaiLieu = tenTaiLieu; }

    public String getDuongDan() { return duongDan; }
    public void setDuongDan(String duongDan) { this.duongDan = duongDan; }

    public String getLoai() { return loai; }
    public void setLoai(String loai) { this.loai = loai; }

    public String getIcon() { return icon; }
    public void setIcon(String icon) { this.icon = icon; }

    public String getMoTa() { return moTa; }
    public void setMoTa(String moTa) { this.moTa = moTa; }
}
